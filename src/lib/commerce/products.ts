import { slugify } from "@/lib/utils/slug";
import { DEFAULT_CURRENCY, DEFAULT_RETURN_POLICY, DEFAULT_SHIPPING_ESTIMATE, resolvePurchaseMode } from "./config";
import type {
  Authentication,
  Money,
  Product,
  ProductFilters,
  ProductImage,
  ProductSort,
} from "./types";

function money(amount: number): Money {
  return { amount, currency: DEFAULT_CURRENCY };
}

function authentication(certified: boolean): Authentication {
  return certified
    ? {
        checkedInStore: true,
        provider: "Entrupy",
        certificateAvailable: true,
        invoiceAvailable: true,
      }
    : {
        checkedInStore: true,
        certificateAvailable: false,
        invoiceAvailable: true,
      };
}

function images(brand: string, title: string, count = 3, realSrc?: string): ProductImage[] {
  const alt = `${brand} ${title}`;
  if (realSrc) {
    return [{ url: realSrc, alt, width: 378, height: 473 }];
  }
  return Array.from({ length: count }, (_, i) => ({
    url: "placeholder",
    alt: i === 0 ? alt : `${alt} — detail ${i + 1}`,
    width: 1200,
    height: 1500,
  }));
}

type SeedProduct = Omit<
  Product,
  | "price"
  | "purchaseMode"
  | "images"
  | "thumbnail"
  | "authentication"
  | "shipping"
  | "returnPolicy"
  | "quantity"
> & {
  priceAmount: number;
  purchaseModeOverride?: Product["purchaseMode"];
  certified?: boolean;
  imageCount?: number;
  /** Real photo path (e.g. "/goyard-vendome-pouch.png"). Falls back to the gradient placeholder when omitted. */
  imageSrc?: string;
  quantity?: number;
};

function seed(p: SeedProduct): Product {
  return {
    ...p,
    price: money(p.priceAmount),
    purchaseMode: p.purchaseModeOverride ?? resolvePurchaseMode(p.priceAmount),
    images: images(p.brand, p.title, p.imageCount, p.imageSrc),
    thumbnail: images(p.brand, p.title, 1, p.imageSrc)[0],
    authentication: authentication(p.certified ?? false),
    shipping: DEFAULT_SHIPPING_ESTIMATE,
    returnPolicy: DEFAULT_RETURN_POLICY,
    quantity: p.quantity ?? (p.availability === "sold" ? 0 : 1),
  };
}

