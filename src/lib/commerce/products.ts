export function getAllProducts(): Product[] {
  return PRODUCTS;
}

export function getProductByHandle(handle: string): Product | undefined {
  return PRODUCTS.find((p) => p.handle === handle);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getFeaturedProducts(limit = 4): Product[] {
  return PRODUCTS.filter((p) => p.featured).slice(0, limit);
}

export function getNewArrivals(limit = 8): Product[] {
  return [...PRODUCTS]
    .filter((p) => p.newArrival)
    .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1))
    .slice(0, limit);
}

export function getEditorPicks(limit = 6): Product[] {
  return PRODUCTS.filter((p) => p.editorPick).slice(0, limit);
}

export function getProductsByDesigner(designerHandle: string): Product[] {
  return PRODUCTS.filter((p) => p.designerHandle === designerHandle);
}

export function getProductsByCategory(category: string): Product[] {
  return PRODUCTS.filter((p) => p.category === category);
}

export function getProductsByCollection(collectionId: string): Product[] {
  return PRODUCTS.filter((p) => p.collectionIds.includes(collectionId));
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return PRODUCTS.filter(
    (p) =>
      p.id !== product.id &&
      (p.category === product.category || p.designerHandle === product.designerHandle)
  ).slice(0, limit);
}

export function searchProducts(query: string, limit = 12): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PRODUCTS.filter((p) =>
    [p.title, p.brand, p.category, p.subcategory ?? "", p.sku]
      .join(" ")
      .toLowerCase()
      .includes(q)
  ).slice(0, limit);
}

export function filterProducts(filters: ProductFilters, sort: ProductSort = "newest"): Product[] {
  let results = [...PRODUCTS];

  if (filters.category) results = results.filter((p) => p.category === filters.category);
  if (filters.designerHandle) results = results.filter((p) => p.designerHandle === filters.designerHandle);
  if (filters.designerHandles?.length) {
    results = results.filter((p) => filters.designerHandles!.includes(p.designerHandle));
  }
  if (filters.subcategory?.length) {
    results = results.filter((p) => p.subcategory && filters.subcategory!.includes(slugify(p.subcategory)));
  }
  if (filters.collectionHandle) {
    results = results.filter((p) => p.collectionIds.includes(filters.collectionHandle!));
  }
  if (filters.gender) results = results.filter((p) => p.gender === filters.gender || p.gender === "unisex");
  if (filters.condition?.length) results = results.filter((p) => filters.condition!.includes(p.condition));
  if (filters.availability?.length) {
    results = results.filter((p) => filters.availability!.includes(p.availability));
  }
  if (filters.colour?.length) {
    results = results.filter((p) => p.colour && filters.colour!.includes(p.colour));
  }
  if (filters.size?.length) {
    results = results.filter((p) => p.size && filters.size!.includes(p.size));
  }
  if (typeof filters.priceMin === "number") {
    results = results.filter((p) => p.price.amount >= filters.priceMin!);
  }
  if (typeof filters.priceMax === "number") {
    results = results.filter((p) => p.price.amount <= filters.priceMax!);
  }
  if (filters.query) {
    const q = filters.query.trim().toLowerCase();
    results = results.filter((p) => [p.title, p.brand].join(" ").toLowerCase().includes(q));
  }

  switch (sort) {
    case "price_asc":
      results.sort((a, b) => a.price.amount - b.price.amount);
      break;
    case "price_desc":
      results.sort((a, b) => b.price.amount - a.price.amount);
      break;
    case "newest":
      results.sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1));
      break;
    default:
      break;
  }

  return results;
}
